CREATE TABLE IF NOT EXISTS import_batches (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 client_key VARCHAR(80) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 UNIQUE (user_id, client_key)
);
CREATE TABLE IF NOT EXISTS private_images (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 storage_key CHAR(48) NOT NULL UNIQUE,
 sha256 CHAR(64) NOT NULL,
 original_name VARCHAR(255) NOT NULL,
 mime VARCHAR(40) NOT NULL,
 bytes BIGINT UNSIGNED NOT NULL,
 width INT NOT NULL,
 height INT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 INDEX (user_id, sha256)
);
CREATE TABLE IF NOT EXISTS import_items (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 batch_id BIGINT UNSIGNED NOT NULL,
 client_key VARCHAR(80) NOT NULL,
 filename VARCHAR(255) NOT NULL,
 state VARCHAR(30) NOT NULL DEFAULT 'queued',
 image_id BIGINT UNSIGNED NULL,
 suggestion JSON NULL,
 fields JSON NULL,
 human_edits JSON NULL,
 reviewed BOOLEAN NOT NULL DEFAULT FALSE,
 linked_edition_id BIGINT UNSIGNED NULL,
 approved_at TIMESTAMP NULL,
 error VARCHAR(500) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (batch_id) REFERENCES import_batches(id),
 FOREIGN KEY (image_id) REFERENCES private_images(id),
 FOREIGN KEY (linked_edition_id) REFERENCES editions(id),
 UNIQUE (batch_id, client_key), INDEX (batch_id, state)
);
CREATE TABLE IF NOT EXISTS import_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 item_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(40) NOT NULL,
 payload JSON NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (item_id) REFERENCES import_items(id),
 FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS auth_limits (
 address_hash CHAR(64) PRIMARY KEY,
 attempts INT NOT NULL DEFAULT 0,
 window_start TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
