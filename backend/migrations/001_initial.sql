CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS puzzles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(255) NOT NULL,
 subject VARCHAR(120) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS editions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 puzzle_id BIGINT UNSIGNED NOT NULL,
 manufacturer VARCHAR(160) NOT NULL,
 sku VARCHAR(100) NULL,
 barcode VARCHAR(100) NULL,
 release_year SMALLINT UNSIGNED NULL,
 piece_count INT UNSIGNED NULL,
 width_mm INT UNSIGNED NULL,
 height_mm INT UNSIGNED NULL,
 FOREIGN KEY (puzzle_id) REFERENCES puzzles(id),
 INDEX (manufacturer), INDEX (barcode)
);
CREATE TABLE IF NOT EXISTS owned_copies (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 edition_id BIGINT UNSIGNED NOT NULL,
 box_condition VARCHAR(50) NULL,
 seal_status VARCHAR(50) NULL,
 completeness VARCHAR(50) NULL,
 storage_location VARCHAR(255) NULL,
 purchase_price DECIMAL(12,2) NULL,
 estimated_value DECIMAL(12,2) NULL,
 currency CHAR(3) NOT NULL DEFAULT 'CAD',
 notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (edition_id) REFERENCES editions(id),
 INDEX (user_id, edition_id)
);
